package hostbridge

import (
	"encoding/json"
	"strings"
	"testing"
)

func TestAuthorityWireV1(t *testing.T) {
	binding := AuthorityBinding{
		GoalID: "goal-1", MutationID: "mutation-1", WriterGeneration: 2,
		Owner: "writer", Session: "session-1", Provider: "cloudflare", Operation: "operation-1",
		ResourceDigest: strings.Repeat("1", 64), TargetDigest: strings.Repeat("2", 64),
		PlanDigest: strings.Repeat("3", 64), GrantDigest: strings.Repeat("4", 64),
	}
	req := authorityRequest{1, "request-1", "preview_admission", binding}
	expiry := "2026-11-11T12:01:00Z"
	advisory := authorityAdvisory{
		Version: 1, RequestID: req.RequestID, Status: "ADVISORY", Reason: "EXECUTION_FENCE_UNAVAILABLE",
		AuthorityBinding: binding, ExpiresAt: &expiry,
	}
	// Generated by workspace-infra's _advisory_digest (v1).
	const advisoryDigest = "ba07dd120070d46dcf1c542da2642d970c73f9c979d25c289dc620def45e25de"
	reply := authorityReply{authorityAdvisory: advisory, AdmissionDigest: ptr(advisoryDigest)}
	raw, _ := json.Marshal(reply)
	if _, err := validateAuthorityReply(req, raw); err != nil {
		t.Fatalf("Python v1 advisory rejected: %v", err)
	}
	for name, bad := range map[string]string{
		"duplicate":            strings.Replace(string(raw), "{", "{\"v\":1,", 1),
		"extra":                strings.Replace(string(raw), "{", "{\"extra\":1,", 1),
		"trailing":             string(raw) + "{}",
		"mismatched":           strings.Replace(string(raw), "mutation-1", "mutation-2", 1),
		"changed advisory":     strings.Replace(string(raw), expiry, "2026-11-11T12:01:01Z", 1),
		"unexpected authority": strings.Replace(string(raw), "false", "true", 1),
		"missing boolean":      strings.Replace(string(raw), "false", "null", 1),
		"oversized":            string(raw) + strings.Repeat(" ", localMaxFrame),
	} {
		t.Run(name, func(t *testing.T) {
			if _, err := validateAuthorityReply(req, []byte(bad)); err != ErrLocalAuthorityInvalid {
				t.Fatalf("reply should be rejected, got %v", err)
			}
		})
	}
	req.Method = "preview_execution"
	if _, err := validateAuthorityReply(req, raw); err != nil {
		t.Fatalf("Python v1 execution preview rejected: %v", err)
	}
	reply.Status, reply.Reason = "OK", "EXECUTION_OBSERVED"
	reply.ExpiresAt, reply.AdmissionDigest = nil, nil
	reply.MutationState = ptr("RUNNING")
	raw, _ = json.Marshal(reply)
	if _, err := validateAuthorityReply(req, raw); err != ErrLocalAuthorityInvalid {
		t.Fatalf("unexpected mutation response accepted: %v", err)
	}
}

func ptr(value string) *string { return &value }
